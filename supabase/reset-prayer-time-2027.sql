-- 기도시간 전체 초기화 (2027 정식 시작용) — ⚠️ 한 번만, 수동으로 실행
-- ============================================================
-- 목적:
--   테스트 기간 동안 쌓인 모든 기도시간을 0으로 리셋하여,
--   2027년 정식 공개일부터 깨끗하게 새로 누적을 시작합니다.
--   (이후에는 별도 작업 없이 계속 누적됩니다 — 매년 리셋 아님)
--
-- 실행 위치: Supabase 대시보드 → SQL Editor → 아래 전체를 붙여넣고 Run
-- 실행 시점: 2027년 교회에 "정식 공개하는 날" 단 한 번만.
--
-- ⚠️ 경고: 되돌릴 수 없습니다!
--   - 모든 성도의 개인 기도 기록이 삭제됩니다.
--   - 공동 기도제목의 '누적 시간'이 0으로 초기화됩니다.
--     (기도제목 글 자체는 그대로 남고, 쌓인 '시간'만 0이 됩니다.)
-- ============================================================

begin;

-- 1) 개인 기도 기록 전체 삭제 (모든 성도의 날짜별 기도시간)
delete from public.prayer_time;

-- 2) 공동 기도제목의 누적 시간만 0으로 (기도제목 글은 유지)
update public.communal_prayers set total_minutes = 0;

commit;

-- 3) 확인용: 교회 총 누적 기도시간(초)이 0인지 확인합니다.
--    아래 결과가 0 이면 초기화 성공입니다.
select
  coalesce((select sum(minutes) from public.prayer_time), 0)
  + coalesce((select sum(total_minutes) from public.communal_prayers), 0)
  as church_total_seconds;
