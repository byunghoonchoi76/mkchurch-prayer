/** 본문 참조(예: "시편 3-4")를 대한성서공회 성경읽기(개역개정) 주소로 바꿉니다. */
export function bskoreaUrl(reference: string): string {
  const [book, rest = ''] = reference.trim().split(/\s+/);
  const code = USFM[book];
  const chap = (rest.match(/^\d+/) ?? ['1'])[0];
  if (!code) return `https://www.google.com/search?q=${encodeURIComponent(`${reference} 개역개정 성경`)}`;
  return `https://www.bskorea.or.kr/bible/korbibReadpage.php?version=GAE&book=${code}&chap=${chap}`;
}
