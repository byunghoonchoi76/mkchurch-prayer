export function mccheyneIndex(date: Date = new Date()): number {
  const m = date.getMonth();
  const d = date.getDate();
  let idx = MONTH_OFFSET[m] + (d - 1);
  if (m === 1 && d === 29) idx = MONTH_OFFSET[1] + 27; // 윤년 2/29 → 2/28 읽기
  return Math.max(0, Math.min(364, idx));
}

/** 그 날짜의 읽을 본문 4곳 [가정1, 가정2, 개인1, 개인2] */
export function mccheyneForDate(date: Date = new Date()): readonly [string, string, string, string] {
  return MCHEYNE_PLAN[mccheyneIndex(date)];
}

